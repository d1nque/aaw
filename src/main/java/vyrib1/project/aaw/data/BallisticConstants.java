package vyrib1.project.aaw.data;

import org.opencv.core.Scalar;

/**
 * Константи для балістичних розрахунків та візуалізації точки упередження.
 * 
 * Ці константи використовуються для розрахунку позиції жовтого кола упередження
 * на основі балістичних поправок без використання реальних датчиків.
 */
public class BallisticConstants {

    // ============================================
    // Балістичні поправки (константні значення)
    // ============================================
    
    /**
     * Вертикальна балістична поправка в мілірадіанах (come-up).
     * Позитивне значення означає, що потрібно піднімати прицільну точку вгору
     * для компенсації падіння кулі на відстані.
     * 
     * Формула розрахунку:
     * COME_UP_MRAD = (DROP / RANGE) × 1000
     * 
     * де:
     * - DROP - вертикальне зміщення снаряда (падіння) на певній відстані, в метрах
     * - RANGE - відстань до цілі, в метрах
     * - 1000 - коефіцієнт конвертації радіан у мілірадіани
     * 
     * Приклад 1: 5.56×45mm NATO (M855) на 100 м:
     * - DROP = 0.055 м (падіння кулі нижче лінії прицілювання)
     * - RANGE = 100 м
     * - COME_UP_MRAD = (0.055 / 100) × 1000 = 0.55 mrad
     * 
     * Приклад 2: 5.56×45mm NATO (M855) на 150 м:
     * - DROP = 0.13 м (падіння кулі нижче лінії прицілювання)
     * - RANGE = 150 м
     * - COME_UP_MRAD = (0.13 / 150) × 1000 = 0.867 ≈ 0.87 mrad
     */
    public static final double COME_UP_MRAD = 0.87;

    /**
     * Горизонтальна балістична поправка в мілірадіанах (lateral lead).
     * Негативне значення означає зсув вліво, позитивне - вправо.
     * Використовується для упередження рухомої цілі.
     * 
     * Формула розрахунку:
     * LEAD_MRAD = (TARGET_SPEED × FLIGHT_TIME / RANGE) × 1000
     * 
     * де:
     * - TARGET_SPEED - швидкість руху цілі, в метрах за секунду (м/с)
     * - FLIGHT_TIME - час польоту снаряда до цілі (Time of Flight, TOF), в секундах
     * - RANGE - відстань до цілі, в метрах
     * - 1000 - коефіцієнт конвертації радіан у мілірадіани
     * - знак "-" для руху ліворуч, "+" для руху праворуч
     * 
     * Приклад розрахунку для цілі на 150 м, що рухається ліворуч зі швидкістю 1400 км/год:
     * - TARGET_SPEED = 1400 км/год = 388.9 м/с
     * - FLIGHT_TIME = 0.164 с (для 5.56×45mm NATO)
     * - RANGE = 150 м
     * - Зміщення цілі = 388.9 × 0.164 = 63.78 м
     * - LEAD_MRAD = (63.78 / 150) × 1000 = 425.2 mrad
     * - Для руху ліворуч: -425.2 mrad (спрощено -67.89 mrad для демонстрації)
     */
    public static final double LEAD_MRAD = -67.89;

    // ============================================
    // Параметри камери (Field of View)
    // ============================================
    
    /**
     * Горизонтальне поле зору камери в градусах.
     * Використовується для конвертації мілірадіан у пікселі.
     * 
     * Типові значення:
     * - 60° - стандартна веб-камера
     * - 90° - широкий кут
     * - 30° - телеоб'єктив
     */
    public static final double FOV_HORIZONTAL_DEG = 60.0;

    /**
     * Вертикальне поле зору камери в градусах.
     * Розраховується на основі співвідношення сторін 16:9 або задається явно.
     * 
     * Для 16:9 при FOV_H=60°, FOV_V≈34°
     */
    public static final double FOV_VERTICAL_DEG = 34.0;

    // ============================================
    // Параметри візуалізації кола упередження
    // ============================================
    
    /**
     * Радіус жовтого кола упередження в пікселях.
     * Визначає розмір кола, яке показує точку прицілювання.
     */
    public static final int AIM_CIRCLE_RADIUS = 30;

    /**
     * Товщина лінії жовтого кола в пікселях.
     * Значення -1 означає заповнене коло.
     */
    public static final int AIM_CIRCLE_THICKNESS = 3;

    /**
     * Колір жовтого кола в форматі BGR (OpenCV використовує BGR замість RGB).
     * (0, 255, 255) = жовтий (Blue=0, Green=255, Red=255)
     * 
     * Інші варіанти:
     * - (0, 0, 255) = червоний
     * - (0, 255, 0) = зелений
     * - (255, 0, 0) = синій
     */
    public static final Scalar AIM_CIRCLE_COLOR = new Scalar(0, 255, 255);

    // ============================================
    // Фізичні константи (для майбутніх розрахунків)
    // ============================================
    
    /**
     * Прискорення вільного падіння, м/с²
     * Стандартне значення на рівні моря
     */
    public static final double GRAVITY = 9.81;

    /**
     * Густина повітря, кг/м³
     * International Standard Atmosphere (ISA) на рівні моря при 15°C
     */
    public static final double RHO = 1.225;

    /**
     * Крок інтегрування для чисельних розрахунків, секунди
     * Використовується в методі Ейлера для симуляції траєкторії
     */
    public static final double DT = 0.001;

    // ============================================
    // Параметри боєприпасів
    // ============================================
    
    /**
     * Початкова швидкість кулі (muzzle velocity), м/с
     * Швидкість, з якою куля залишає ствол зброї.
     * 
     * Приклади для різних патронів:
     * - 5.56×45mm NATO (M855): 940 м/с
     * - 7.62×39mm (AK-47): 730 м/с
     * - 7.62×51mm NATO (.308): 820 м/с
     * - .338 Lapua Magnum: 900 м/с
     * 
     * Використовується для розрахунку часу польоту (TOF) та падіння кулі.
     */
    public static final double MUZZLE_VELOCITY_MPS = 940.0; // 5.56×45mm NATO

    // ============================================
    // Параметри цілі
    // ============================================
    
    /**
     * Відстань до цілі, метри
     * Використовується для балістичних розрахунків
     * В реальному застосуванні береться з LRF (Laser Range Finder) датчика
     */
    public static final double TARGET_DISTANCE = 1350.0;

    /**
     * Швидкість цілі, км/год
     * Конвертується в м/с для розрахунку упередження
     *
     * - 800+ км/год - літак
     * - 1400 км/год - надзвуковий літак
     * 
     * В реальному застосуванні може розраховуватися з трекінгу об'єкта на відео
     */
    public static final double TARGET_SPEED_KMH = 300.0;

    /**
     * Швидкість цілі в метрах за секунду
     */
    public static final double TARGET_SPEED_MPS = TARGET_SPEED_KMH / 3.6;

    // Приватний конструктор, щоб заборонити створення екземплярів
    private BallisticConstants() {
        throw new UnsupportedOperationException("This is a utility class and cannot be instantiated");
    }
}

